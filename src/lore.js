var TALK = {};      // 누를 때마다 다음 줄로 (사람·단계마다)
function pickLine(key, list) {
  if (!list || !list.length) return '';
  var k = TALK[key] || 0; TALK[key] = k + 1;
  return list[k % list.length];
}
function rumor(save) {
  var n = DS.nextScn(save);
  if (!n) return [RUMOR.end];
  if (n.tier > DS.partyTier(save)) {
    var masters = DS.charList(save).filter(function (c) { return DS.CLASSES[c.cls].master || c.L > 70; }).sort(function (a, b) { return b.L - a.L; });
    if (masters.length && DS.tierOfL(masters[0].L) >= n.tier) return ['합일한 집을 앞에 세우게. 변경 성주들은 8단이 아니면 상대도 안 한다네.'];
    return n.tier >= 9 ? tier9Talk(save) : fuseTalk(save);
  }
  return [RUMOR[n.id] || RUMOR.end];
}
function npc(zoneId, i, save) {
  var t = TOWN[zoneId], st = stageOf(save), who = FOLK[zoneId] && FOLK[zoneId][i], c = (save && save.cleared) || {}, list;
  if (!t || !save) return '';
  if (i === 'house') list = t.house[st];
  else if (!t[i]) list = rumor(save);
  else {
    list = t[i][st];
    if (st === 3 && t['f' + i] && DS.charList(save).some(function (x) { return DS.CLASSES[x.cls].master; })) list = t['f' + i].concat(list);
  }
  var ms = DS.charList(save).filter(function (x) { return DS.CLASSES[x.cls].master; }).length;
  var ok = (list || []).filter(function (l) { return typeof l === 'string' || ((!l.at || c[l.at]) && (!l.pre || ms < 3) && (!l.m || ms >= l.m)); });
  list = (ok.length ? ok : list || []).map(function (l) { return typeof l === 'string' ? l : l.t; });
  var line = pickLine(zoneId + ':' + i + ':' + st, list);
  return line && who ? say(who, line) : line;
}


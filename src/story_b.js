function npc(zoneId, i, save) {
  var base = function () { return origNpc ? origNpc(zoneId, i, save) : ''; };
  if (!save || !DS.LORE) return base();
  var who = DS.LORE.folk && DS.LORE.folk[zoneId] && DS.LORE.folk[zoneId][i];
  if (i === 0 || i === '0') {
    var n = DS.nextScn && DS.nextScn(save);
    if (n && RUMOR[n.id] && who) return say(who, RUMOR[n.id]);
    return base();
  }
  var t = TOWN[zoneId] && TOWN[zoneId][i], st = DS.LORE.npcStage ? DS.LORE.npcStage(save) : 0, c = save.cleared || {};
  var ms = DS.charList(save).filter(function (x) { return DS.CLASSES[x.cls].master; }).length;
  var list = ((t && t[st]) || []).filter(function (l) { return typeof l === 'string' || ((!l.at || c[l.at]) && (!l.pre || ms < 3) && (!l.m || ms >= l.m)); })
    .map(function (l) { return typeof l === 'string' ? l : l.t; });
  if (!list.length || !who) return base();
  var key = zoneId + ':' + i + ':' + st, k = TALK[key] || 0; TALK[key] = k + 1;
  k = k % (list.length + 1);
  return k === list.length ? base() : say(who, list[k]);      // 한 바퀴에 한 번은 원래 줄
}

